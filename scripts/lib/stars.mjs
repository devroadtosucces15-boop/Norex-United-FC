// Pull http(s) links out of free text (issue body or inbox.txt); one per line is typical, markdown links work too.
export function extractLinks(text) {
  const found = [];
  for (const m of String(text || '').matchAll(/https?:\/\/[^\s<>)\]"'`]+/g)) {
    const u = m[0].replace(/[.,;:!?]+$/, '');
    try { found.push(new URL(u).href); } catch { /* skip junk */ }
  }
  return [...new Set(found)];
}

export const githubRepoOf = (url) => {
  const u = new URL(url);
  if (u.hostname !== 'github.com') return null;
  const [owner, repo] = u.pathname.split('/').filter(Boolean);
  return owner && repo ? `${owner}/${repo.replace(/\.git$/, '')}` : null;
};

// First real prose paragraph of a README, markdown stripped, short.
export function summariseReadme(md, max = 280) {
  const text = String(md || '').replace(/<!--[\s\S]*?-->/g, '').replace(/```[\s\S]*?```/g, '');
  for (const block of text.split(/\n\s*\n/)) {
    const line = block.trim();
    if (!line || /^(#|\||>|!\[|\[!\[|<|[-*]\s|---|===)/.test(line)) continue;
    const plain = line.replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*_`]/g, '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
    if (plain.length < 25) continue;
    return plain.length > max ? plain.slice(0, max - 1).replace(/\s+\S*$/, '') + '…' : plain;
  }
  return '';
}

// Title + description from an HTML page (non-GitHub links)
export function parseHtmlMeta(html) {
  const h = String(html || '').slice(0, 200000);
  const meta = (re) => (h.match(re)?.[1] || '').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, ' ').trim();
  const title = meta(/<meta[^>]+property=["']og:title["'][^>]+content=["']([^"']*)["']/i) || meta(/<title[^>]*>([^<]*)<\/title>/i);
  const description = meta(/<meta[^>]+(?:name|property)=["'](?:og:)?description["'][^>]+content=["']([^"']*)["']/i);
  return { title, description: description.length > 280 ? description.slice(0, 279) + '…' : description };
}

// inbox.md is one bullet per link; re-adding an existing link is a no-op.
export function parseInbox(md) {
  return new Set([...String(md || '').matchAll(/\]\((https?:\/\/[^)\s]+)\)/g)].map((m) => m[1]));
}

export function inboxLine({ url, title, summary, added }) {
  return `- [${clean(title) || url}](${url})${summary ? ` – ${clean(summary)}` : ''} _(added ${added})_`;
}

export function renderInbox(lines) {
  return ['# Link inbox', '', 'Links added by issue (label `link`) or by editing `RESEARCH/inbox.txt`. Newest first.', '', ...lines, ''].join('\n');
}
