// Pure helpers for the stars sync and the link inbox (no network, no fs) so tests can cover them.
// Used by scripts/stars-sync.mjs and scripts/link-inbox.mjs. Output lives in RESEARCH/stars/.

export const MARK = '<!-- generated by scripts/stars-sync.mjs – edit via GitHub star lists, not by hand -->';

export const slugify = (s) =>
  String(s || '').toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'list';

const clean = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();

// One GraphQL repository node -> plain entry
export const repoEntry = (n) => ({
  name: n.nameWithOwner,
  url: n.url,
  description: clean(n.description),
  language: n.primaryLanguage?.name || '',
  updated: (n.pushedAt || '').slice(0, 10),
  stars: n.stargazerCount ?? 0,
});

export function renderList({ name, description, entries }) {
  const rows = [...entries].sort((a, b) => a.name.localeCompare(b.name));
  const out = [MARK, `# ${name}`, ''];
  if (description) out.push(`> ${clean(description)}`, '');
  out.push(`${rows.length} repo${rows.length === 1 ? '' : 's'}`, '', '| Repo | Description | Language | Updated |', '|---|---|---|---|');
  for (const e of rows) out.push(`| [${e.name}](${e.url}) | ${e.description || '–'} | ${e.language || '–'} | ${e.updated || '–'} |`);
  return out.join('\n') + '\n';
}

export function renderIndex(lists) {
  const out = [MARK, '# Starred repos and saved links', '',
    'Synced from GitHub star lists every 6 h (`stars-sync.yml`). Links added through the inbox are in [inbox.md](inbox.md).', '',
    '| List | Repos |', '|---|---|'];
  for (const l of lists) out.push(`| [${l.name}](${l.file}) | ${l.count} |`);
  return out.join('\n') + '\n';
}

// Split starred repos into lists (file name -> list). Anything not in a list goes to "Unsorted".
export function buildLists(stars, lists) {
  const byUrl = new Map(stars.map((s) => [s.url, s]));
  const used = new Set();
  const out = [];
  for (const l of lists) {
    const entries = l.items.map((i) => byUrl.get(i.url) || i).filter(Boolean);
    entries.forEach((e) => used.add(e.url));
    out.push({ name: l.name, description: l.description, file: `${slugify(l.name)}.md`, entries });
  }
  const rest = stars.filter((s) => !used.has(s.url));
  if (rest.length) out.push({ name: 'Unsorted stars', description: 'Starred but not in any list yet.', file: 'unsorted.md', entries: rest });
  return out;
}

